// ============================ MIA · asistente de MeteoIA en la portada ============================
// Mascota flotante (app/mia.webp) que abre un chat con el asistente local (mac/asistente_local.py + Ollama), publicado por el
// túnel de Cloudflare en MIA_URL. Mismo protocolo que el panel de la página Desarrollo (build/asistente_ia.js):
//   GET  /salud      → { ok, modelo, ollama, version }
//   POST /preguntar  → { respuesta, herramientas:[{nombre,pos}], segundos } o { error }
// La consulta va como text/plain para evitar la petición previa (OPTIONS). El límite de consultas por persona lo aplica el
// servidor (5 por minuto, 40 por día). Si el Mac está apagado, MIA lo dice y el resto de la portada sigue igual.
(function () {
  const MIA_URL = 'https://asistente.meteoia.cl';
  const EN = window.METEOIA_LANG === 'en';
  const T = EN ? {
    hola: 'Hi! I\'m MIA. Ask me about the sea 🌊', abrir: 'Talk to MIA, the MeteoIA assistant', cerrar: 'Close',
    sub: 'MeteoIA assistant · local AI', con: 'Connecting with MIA…', ok: 'Online', okMal: 'the AI engine is not responding',
    off: 'MIA is resting: she runs on a local computer that may be off or offline. Try again later.', reint: 'Retry',
    ph: 'Ask about a place and day, warnings, a bay or a route…', env: 'Send', esp: 'Checking the data…',
    perdi: 'Connection with MIA was lost', sinR: 'no answer in 3 min', vacio: 'No answer.',
    bienv: 'Hi! I\'m MIA, the MeteoIA assistant. I answer with the same data shown on this page: wind, sea state, warnings, bay forecasts and routes. Answers are in Spanish.',
    ej: ['How will the sea be in Valparaíso in three days?', 'Are there warnings for Talcahuano?', 'WRF + AI forecast for Puerto Montt bay', 'Can I sail from Puerto Montt today?'],
    como: 'How it works',
    txt: '<p>A language model running on a local computer (Ollama, no paid services) reads your question and calls MeteoIA tools: conditions at a point (Open-Meteo: ECMWF IFS wind, marine wave model), current and upcoming warnings, WRF + AI bay forecast, port status and route comparison. The answer uses only that data and cites the source and time.</p><p>One question at a time (max. 5 per minute and 40 per day per person); each answer may take 10 to 40 s.</p><p><b>Reference information generated by AI from model data. It does not replace the official forecasts and warnings of the Chilean Navy.</b></p>',
    nombres: { condicion_punto: 'point conditions', avisos_vigentes: 'warnings', pronostico_bahia: 'WRF + AI', comparar_rutas: 'routes', tendencia_punto: 'trend', estado_puerto: 'port status' }
  } : {
    hola: '¡Hola! Soy MIA. Pregúntame por el mar 🌊', abrir: 'Conversar con MIA, la asistente de MeteoIA', cerrar: 'Cerrar',
    sub: 'Asistente de MeteoIA · IA local', con: 'Conectando con MIA…', ok: 'En línea', okMal: 'el motor de IA no responde',
    off: 'MIA está descansando: corre en un equipo local que puede estar apagado o sin internet. Intente más tarde.', reint: 'Reintentar',
    ph: 'Pregunte por un lugar y día, avisos, una bahía o una ruta…', env: 'Enviar', esp: 'Consultando los datos…',
    perdi: 'Se perdió la conexión con MIA', sinR: 'sin respuesta en 3 min', vacio: 'Sin respuesta.',
    bienv: '¡Hola! Soy MIA, la asistente de MeteoIA. Respondo con los mismos datos de esta página: viento, estado del mar, avisos, pronóstico de bahías y rutas.',
    ej: ['¿Cómo estará el mar en Valparaíso en tres días?', '¿Hay avisos vigentes para Talcahuano?', 'Pronóstico WRF + IA de la bahía de Puerto Montt', '¿Puedo zarpar hoy de Puerto Montt?'],
    como: 'Cómo funciona',
    txt: '<p>Un modelo de lenguaje que corre en un equipo local (Ollama, sin servicios de pago) interpreta la pregunta y llama a las herramientas de MeteoIA: condición en un punto (Open-Meteo: viento ECMWF IFS, oleaje del modelo marino), avisos vigentes y próximos, pronóstico WRF + IA de bahía, estado de puerto y comparación de rutas. La respuesta se redacta solo con esos datos y cita la fuente y la hora.</p><p>Atiende una consulta a la vez (máximo 5 por minuto y 40 al día por persona); cada respuesta puede tardar de 10 a 40 s. El estado del mar se expresa con la escala de la Armada.</p><p><b>Información referencial generada por IA con datos de modelos. No reemplaza los pronósticos ni los avisos oficiales de la Armada de Chile.</b></p>',
    nombres: { condicion_punto: 'condición en el punto', avisos_vigentes: 'avisos', pronostico_bahia: 'WRF + IA', comparar_rutas: 'rutas', tendencia_punto: 'tendencia', estado_puerto: 'estado de puerto' }
  };
  const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const ses = { get: k => { try { return sessionStorage.getItem(k); } catch (e) { return null; } }, set: (k, v) => { try { sessionStorage.setItem(k, v); } catch (e) {} } };
  const evento = n => { try { window.mnEvento && mnEvento(n); } catch (e) {} };

  // ---- Mascota flotante y globo de saludo
  const raiz = document.createElement('div');
  raiz.id = 'mia'; raiz.dataset.i18n = 'no';
  raiz.innerHTML = `
    <div class="mia-globo" hidden><span>${esc(T.hola)}</span><button type="button" class="mia-gx" aria-label="${esc(T.cerrar)}">✕</button></div>
    <button type="button" class="mia-btn" aria-haspopup="dialog" aria-expanded="false" aria-controls="miaPanel" title="${esc(T.abrir)}">
      <picture><source srcset="app/mia.png" media="(prefers-reduced-motion: reduce)"><img src="app/mia.webp" alt="${esc(T.abrir)}" width="125" height="160" decoding="async" loading="lazy"></picture>
    </button>
    <section class="mia-panel" id="miaPanel" role="dialog" aria-modal="false" aria-labelledby="miaTit" hidden>
      <header class="mia-cab">
        <img src="app/mia_avatar.png" alt="" width="40" height="40">
        <div><b id="miaTit">MIA</b><small>${esc(T.sub)}</small></div>
        <span class="mia-est" aria-live="polite"><i></i><em>${esc(T.con)}</em></span>
        <button type="button" class="mia-x" aria-label="${esc(T.cerrar)}" title="${esc(T.cerrar)} (Esc)">✕</button>
      </header>
      <div class="mia-chat" aria-live="polite"></div>
      <div class="mia-ej" hidden>${T.ej.map(t => `<button type="button">${esc(t)}</button>`).join('')}</div>
      <form class="mia-f" hidden><textarea rows="2" maxlength="1000" placeholder="${esc(T.ph)}" aria-label="${esc(T.ph)}"></textarea><button type="submit">${esc(T.env)}</button></form>
      <details class="mia-como"><summary>${esc(T.como)}</summary>${T.txt}</details>
    </section>`;
  document.body.appendChild(raiz);

  const btn = raiz.querySelector('.mia-btn'), globo = raiz.querySelector('.mia-globo'), panel = raiz.querySelector('.mia-panel'),
        chat = panel.querySelector('.mia-chat'), ej = panel.querySelector('.mia-ej'), form = panel.querySelector('.mia-f'),
        q = form.querySelector('textarea'), enviarBtn = form.querySelector('button'), est = panel.querySelector('.mia-est');
  const hist = [];
  let listo = false, ocupado = false, marcas = null;

  // Saludo una vez por sesión, a los 4 s, y se va solo a los 12 s.
  if (!ses.get('mia_globo')) setTimeout(() => {
    if (!panel.hidden) return;
    globo.hidden = false; ses.set('mia_globo', '1');
    setTimeout(() => { globo.hidden = true; }, 12000);
  }, 4000);
  globo.querySelector('.mia-gx').onclick = e => { e.stopPropagation(); globo.hidden = true; };
  globo.querySelector('span').onclick = () => abrir();

  btn.onclick = () => (panel.hidden ? abrir() : cerrar());
  panel.querySelector('.mia-x').onclick = () => cerrar();
  document.addEventListener('keydown', e => { if (e.key === 'Escape' && !panel.hidden) cerrar(); });

  function abrir() {
    panel.hidden = false; globo.hidden = true; raiz.classList.add('abierto'); btn.setAttribute('aria-expanded', 'true');
    if (!chat.children.length) burbuja(T.bienv, 'mia-a');
    evento('mia');
    if (!listo) conectar(); else q.focus();
  }
  function cerrar() {
    panel.hidden = true; raiz.classList.remove('abierto'); btn.setAttribute('aria-expanded', 'false'); btn.focus();
  }
  function estado(cls, html) { est.className = 'mia-est ' + cls; est.querySelector('em').innerHTML = html; }

  async function conectar() {
    estado('', esc(T.con));
    try {
      const r = await fetch(MIA_URL + '/salud', { cache: 'no-store', signal: AbortSignal.timeout(10000) });
      if (!r.ok) throw new Error('HTTP ' + r.status);
      const s = await r.json();
      listo = true;
      estado(s.ollama ? 'on' : 'mal', s.ollama ? esc(T.ok) : esc(T.okMal));
      form.hidden = false; if (chat.children.length < 2) ej.hidden = false;
      q.focus();
    } catch (e) {
      listo = false;
      estado('off', esc(T.off) + ` <button type="button" class="mia-reint">${esc(T.reint)}</button>`);
      est.querySelector('.mia-reint').onclick = conectar;
      form.hidden = true; ej.hidden = true;
    }
  }

  function burbuja(txt, cls) {
    const d = document.createElement('div'); d.className = 'mia-m ' + cls; d.textContent = txt;
    chat.appendChild(d); chat.scrollTop = chat.scrollHeight; return d;
  }

  // Posiciones consultadas en el mapa de la portada (si existe), como en la página Desarrollo.
  function marcar(herr) {
    if (typeof L === 'undefined' || typeof map === 'undefined') return;
    const pts = herr.map(x => x.pos).filter(p => Array.isArray(p) && isFinite(p[1]) && isFinite(p[2]));
    if (!pts.length) return;
    if (!marcas) marcas = L.layerGroup().addTo(map);
    marcas.clearLayers();
    pts.forEach(([n, la, lo]) => L.circleMarker([la, lo], { radius: 8, color: '#0f2a44', weight: 2, fillColor: '#3fa9f5', fillOpacity: .9 })
      .bindTooltip('MIA · ' + esc(n), { direction: 'top' }).addTo(marcas));
    const [, la, lo] = pts[pts.length - 1];
    map.flyTo([la, lo], Math.max(map.getZoom(), 8), { duration: .8 });
  }

  async function enviar(t) {
    t = (t || '').trim();
    if (!t || ocupado || !listo) return;
    ocupado = true; ej.hidden = true; enviarBtn.disabled = true;
    burbuja(t, 'mia-u'); q.value = '';
    const d = burbuja(T.esp, 'mia-a mia-espera');
    raiz.classList.add('pensando');
    try {
      const r = await fetch(MIA_URL + '/preguntar', { method: 'POST', headers: { 'Content-Type': 'text/plain;charset=UTF-8' },
        body: JSON.stringify({ pregunta: t, historial: hist.slice(-6) }), signal: AbortSignal.timeout(180000) });
      const j = await r.json();
      d.classList.remove('mia-espera');
      d.textContent = j.respuesta || j.error || T.vacio;
      if (!j.respuesta) d.classList.add('mia-err');
      const herr = j.herramientas || [];
      const pie = [herr.map(x => T.nombres[x.nombre] || x.nombre).join(' → '), j.segundos ? `${String(j.segundos).replace('.', EN ? '.' : ',')} s` : ''].filter(Boolean).join(' · ');
      if (pie) { const p = document.createElement('div'); p.className = 'mia-h'; p.textContent = pie; d.appendChild(p); }
      if (j.respuesta) hist.push({ rol: 'usuario', texto: t }, { rol: 'asistente', texto: j.respuesta });
      marcar(herr);
      chat.scrollTop = chat.scrollHeight;
    } catch (e) {
      d.classList.remove('mia-espera'); d.classList.add('mia-err');
      d.textContent = `${T.perdi} (${e.name === 'TimeoutError' ? T.sinR : e.message}).`;
      conectar();
    } finally {
      ocupado = false; enviarBtn.disabled = false; raiz.classList.remove('pensando');
    }
  }
  form.onsubmit = e => { e.preventDefault(); enviar(q.value); };
  q.addEventListener('keydown', e => { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); enviar(q.value); } });
  ej.querySelectorAll('button').forEach(b => { b.onclick = () => enviar(b.textContent); });

  // ?mia en la dirección abre el chat directamente (útil para compartir el enlace).
  if (new URLSearchParams(location.search).has('mia')) abrir();
})();
